async function seedQuestionChoice() {
    const existingRecords = await listQuestionChoice();
    const existingId = new Set(existingRecords.map((record) =>record.choice_id));

    let insertedCount = 0;
    for (const choiceInput of SEED_QUESTION_CHOICE) {
        if (existingId.has(choiceInput.choice_id)) {
            continue;
        }

        await createQuestionChoice(choiceInput);
        insertedCount += 1;
    }

    console.log(`Seeded ${insertedCount} questions choice record(s).`);
}

seedQuestionChoice().catch((error) => {
    console.error('Failed to seed question choice.', error);
    process.exitCode = 1;
});
